/// Espaçamentos e raios usados nas telas do Figma (grade de 4px).
abstract final class AppSpacing {
  /// 4px.
  static const double xxs = 4;

  /// 8px.
  static const double xs = 8;

  /// 12px.
  static const double sm = 12;

  /// 16px — margem lateral das telas e padding interno de cards.
  static const double md = 16;

  /// 24px.
  static const double lg = 24;

  /// 32px — espaço entre blocos principais da tela.
  static const double xl = 32;

  /// Raio de tags pequenas e checkboxes.
  static const double radiusXs = 4;

  /// Raio de botões, inputs e cards internos.
  static const double radiusSm = 8;

  /// Raio de cards e do botão principal.
  static const double radiusMd = 12;

  /// Raio "pill" de chips e badges.
  static const double radiusFull = 9999;

  /// Altura da top bar.
  static const double topBarHeight = 64;
}
